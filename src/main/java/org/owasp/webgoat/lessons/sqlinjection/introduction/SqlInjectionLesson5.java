package org.owasp.webgoat.lessons.sqlinjection.introduction;

import static org.owasp.webgoat.container.assignments.AttackResultBuilder.failed;
import static org.owasp.webgoat.container.assignments.AttackResultBuilder.success;

import java.util.Set;
import org.owasp.webgoat.container.assignments.AssignmentEndpoint;
import org.owasp.webgoat.container.assignments.AssignmentHints;
import org.owasp.webgoat.container.assignments.AttackResult;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseBody;
import org.springframework.web.bind.annotation.RestController;

@RestController
@AssignmentHints(
    value = {
      "SqlStringInjectionHint5-1",
      "SqlStringInjectionHint5-2",
      "SqlStringInjectionHint5-3",
      "SqlStringInjectionHint5-4"
    })
public class SqlInjectionLesson5 implements AssignmentEndpoint {

  private static final Set<String> SAFE_PRIVILEGE_PREVIEWS = Set.of("preview-select-grant");

  @PostMapping("/SqlInjection/attack5")
  @ResponseBody
  public AttackResult completed(@RequestParam("privilege_action") String privilegeAction) {
    if (privilegeAction == null || !SAFE_PRIVILEGE_PREVIEWS.contains(privilegeAction)) {
      return failed(this).feedback("sql-injection.5.failed").build();
    }
    return success(this).feedback("sql-injection.5.simulated").build();
  }
}
